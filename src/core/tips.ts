export function selectPreGameTip(
  hasSeenFirstTip: boolean,
  rng: () => number = Math.random
): string {
  if (!hasSeenFirstTip) {
    return GAME_TIPS[0];
  }
  const idx = Math.max(0, Math.min(GAME_TIPS.length - 1, Math.floor(rng() * GAME_TIPS.length)));
  return GAME_TIPS[idx];
}

export function clampStartLevel(level: number, params: GameParams = GAME_PARAMS): number {
  const { minStartLevel, maxStartLevel, defaultStartLevel } = params.threat;
  if (!Number.isFinite(level)) {
    return defaultStartLevel;
  }
  return Math.max(minStartLevel, Math.min(maxStartLevel, Math.round(level)));
}

export function formatStartLevel(level: number): string {
  const safe = Number.isFinite(level) ? Math.round(level) : 0;
  return safe > 0 ? `+${safe}` : `${safe}`;
}
